"""Write src/skillfetch/resolve/plurals.txt: the plural words normalize_term may singularize.

A word ending in -s is singularized only when its singular form also occurs in the
corpus vocabulary (constraints.md §3, norm): "tests" and "test" both occur, so they are
one term; the closed vocabulary's words count in both forms; "https" is never "http"
(stoplist), and a word whose stem never occurs keeps its -s. The vocabulary is every
word of the constraint fields that normalize_term reads (subject, object, object_raw,
condition, artifact) in the index and the fixture corpus, plus the closed vocabulary's
own terms. Run after a rebuild:

    uv run python scripts/plural_words.py [--index data/index]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from skillfetch.resolve.terms import PLURALS_FILE, STOPLIST, singular_candidate
from skillfetch.resolve.vocabulary import VOCABULARY

ROOT = Path(__file__).resolve().parents[1]
WORD = re.compile(r"[a-z0-9]+")
FIELDS = ("subject", "object", "object_raw")
SCOPE = ("condition", "artifact")


def words_of(c: dict) -> set[str]:
    out = set()
    for text in [*(c.get(f) for f in FIELDS), *((c.get("scope") or {}).get(f) for f in SCOPE)]:
        if isinstance(text, str):
            out |= set(WORD.findall(text.lower()))
    return out


def vocabulary_words() -> set[str]:
    """The closed vocabulary's words in both forms: a term is one term however a skill
    inflects it ("docstring" is `docstrings`)."""
    out = set()
    for t in VOCABULARY:
        texts = [t.name, *(t.objects or ()), *(c for e in t.ecosystems for c in e.choices)]
        for text in texts:
            for w in WORD.findall(text.lower()):
                out |= {w, singular_candidate(w)}
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--index", type=Path, default=ROOT / "data" / "index")
    args = parser.parse_args()
    words = vocabulary_words()
    for line in (args.index / "constraints.jsonl").open():
        words |= words_of(json.loads(line))
    for path in (ROOT / "tests" / "fixtures").rglob("constraints.json"):
        for c in json.loads(path.read_text()).get("constraints", []):
            words |= words_of(c)
    plurals = sorted(
        w
        for w in words
        if (stem := singular_candidate(w)) != w and stem in words and w not in STOPLIST
    )
    header = (
        "# Generated by scripts/plural_words.py from the index constraints, the fixture\n"
        "# corpus and the vocabulary: plurals whose singular also occurs. Do not edit.\n"
    )
    PLURALS_FILE.write_text(header + "".join(f"{w}\n" for w in plurals))
    print(f"{len(plurals)} plurals from {len(words)} words -> {PLURALS_FILE}")


if __name__ == "__main__":
    main()
